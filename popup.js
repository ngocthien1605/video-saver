// Writes a Netscape cookies.txt with the cookies for the media host and the page,
// and returns its absolute path on disk.
async function exportCookies(it) {
  const urls = new Set([it.url, it.hdr && it.hdr.referer, it.page, tab.url].filter((u) => /^https?:/.test(u || '')));
  let top;
  try { top = new URL(tab.url).origin; } catch {}
  const all = new Map();
  for (const url of urls) {
    for (const q of [{ url }, top ? { url, partitionKey: { topLevelSite: top } } : null]) {
      if (!q) continue;
      try {
        for (const c of await chrome.cookies.getAll(q)) all.set(`${c.domain}|${c.path}|${c.name}`, c);
      } catch {}
    }
  }
  if (!all.size) return null;
  const lines = ['# Netscape HTTP Cookie File', '# Generated by Stream Saver. Contains login cookies: keep private.', ''];
  for (const c of all.values()) {
    const dom = c.hostOnly ? c.domain.replace(/^\./, '') : c.domain.startsWith('.') ? c.domain : '.' + c.domain;
    lines.push([
      (c.httpOnly ? '#HttpOnly_' : '') + dom,
      c.hostOnly ? 'FALSE' : 'TRUE',
      c.path,
      c.secure ? 'TRUE' : 'FALSE',
      c.session ? 0 : Math.floor(c.expirationDate || 0),
      c.name,
      c.value,
    ].join('\t'));
  }
  const id = await chrome.downloads.download({
    url: 'data:text/plain;charset=utf-8,' + encodeURIComponent(lines.join('\n') + '\n'),
    filename: 'stream-saver-cookies.txt',
    conflictAction: 'overwrite',
    saveAs: false,
  });
  for (let i = 0; i < 30; i++) {
    const [d] = await chrome.downloads.search({ id });
    if (d && d.state === 'complete') return d.filename;
    if (d && d.state === 'interrupted') throw new Error('Could not save cookies file: ' + d.error);
    await sleep(100);
  }
  return 'stream-saver-cookies.txt';
}

async function ytdlp(it, btn) {
  btn.textContent = '…';
  try {
    const cookiePath = await exportCookies(it);
    const cmd = ytdlpStreamCommand({ item: it, tabUrl: tab.url, title: tab.title, ua: navigator.userAgent, cookiePath, win: isWin() });
    $('#cmd').value = cmd;
    $('#out').hidden = false;
    $('#cmd').select();
    await copy(cmd, btn);
  } catch (e) {
    btn.textContent = 'Failed';
    btn.title = e.message;
  }
}

