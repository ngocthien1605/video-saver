function cmd(frameId, name, args) {
  chrome.tabs.sendMessage(tab.id, { type: MSG.MSE_CMD, cmd: name, args }, { frameId: +frameId }).catch(() => {});
}

function render(d) {
  d = d || { items: {}, mse: {} };
  const items = $('#items');
  items.replaceChildren();
  const order = { hls: 0, dash: 1, mp4: 2, webm: 3, audio: 4 };
  const list = Object.values(d.items).sort((a, b) => order[a.kind] - order[b.kind] || (b.t || 0) - (a.t || 0));
  for (const it of list) {
    const stream = it.kind === 'hls' || it.kind === 'dash';
    const auth = it.hdr ? Object.keys(it.hdr).filter((k) => k !== 'user-agent').length : 0;
    const exp = expiryOf(it.url);
    const expTxt = !exp ? '' : exp < Date.now() ? '⚠ link EXPIRED, replay video' : `signed until ${new Date(exp).toLocaleTimeString()}`;
    items.append(
      row(it.kind.toUpperCase(), fileName(it.url), [host(it.url), fmt(it.size), expTxt, auth ? `${auth} header(s)` : ''].filter(Boolean).join(' · '), [
        [stream ? 'Open' : 'Download', (e) => (stream ? openDownloader(it) : directDownload(it, e.target)), 'primary'],
        ['yt-dlp', (e) => ytdlp(it, e.target), '', 'Save a cookies file and copy a yt-dlp command that includes the page’s headers'],
        ['Copy', (e) => copy(it.url, e.target, '✓'), '', 'Copy URL'],
      ])
    );
  }
  if (!list.length) {
    const p = document.createElement('div');
    p.className = 'empty';
    p.textContent = 'Nothing detected yet. Start playing the video, then reopen this popup.';
    items.append(p);
  }

  const mse = $('#mse');
  mse.replaceChildren();
  let any = false;
  for (const [fid, st] of Object.entries(d.mse || {})) {
    if (st.eme) {
      any = true;
      const w = document.createElement('div');
      w.className = 'warn';
      w.textContent = `🔒 This player uses DRM (Encrypted Media Extensions)${+fid ? ` in frame ${fid}` : ''}. Capture is disabled for protected content.`;
      mse.append(w);
      continue;
    }
    const tracks = (st.tracks || []).filter((t) => t.bytes > 0);
    const blobs = st.blobs || [];
    if (!tracks.length && !blobs.length) continue;
    any = true;
    if (tracks.length) {
      const tools = document.createElement('div');
      tools.className = 'tools';
      const turbo = document.createElement('button');
      turbo.textContent = 'Turbo 16× (muted)';
      turbo.title = 'Speeds up playback so the player buffers the whole video faster';
      turbo.onclick = () => cmd(fid, 'turbo');
      const reset = document.createElement('button');
      reset.textContent = 'Reset capture';
      reset.title = 'Drop captured media (keeps init segments). Use before replaying from the start.';
      reset.onclick = () => cmd(fid, 'reset');
      tools.append(turbo, reset);
      mse.append(tools);
    }
    for (const t of tracks) {
      mse.append(
        row('MSE', t.mime, `${fmt(t.bytes)} · ${t.chunks} chunks${+fid ? ` · frame ${fid}` : ''}`, [
          ['Save', () => cmd(fid, 'save-track', { id: t.id, name: safe(tab.title) }), 'primary'],
        ])
      );
    }
    for (const b of blobs) {
      mse.append(
        row('BLOB', b.type || 'blob', fmt(b.size), [
          ['Save', () => cmd(fid, 'save-blob', { id: b.id, name: safe(tab.title) }), 'primary'],
        ])
      );
    }
  }
  if (!any) {
    const p = document.createElement('div');
    p.className = 'empty';
    p.textContent = 'No player buffers captured. Reload the page with the extension enabled and play the video.';
    mse.append(p);
  }
}

const SITES = /^https?:\/\/([^/]*\.)?(youtube\.com|youtu\.be|facebook\.com|fb\.watch|tiktok\.com|x\.com|twitter\.com|instagram\.com|xiaohongshu\.com|xhslink\.com|vimeo\.com|twitch\.tv|reddit\.com|bilibili\.com|dailymotion\.com|soundcloud\.com|pinterest\.com|drive\.google\.com)(\/|$)/;

async function load() {
  [tab] = await chrome.tabs.query({ active: true, currentWindow: true });
  render(await readTab(tab.id));
  const share = shareDirectUrl(tab.url || '');
  $('#sharebtn').hidden = !share;
  if (share || SITES.test(tab.url || '')) $('#site').hidden = false;
}

const pageCmd = (audio) => async (e) => {
  const c = ytdlpPageCommand({ url: tab.url, win: isWin(), audio });
  $('#cmd').value = c;
  $('#out').hidden = false;
  await copy(c, e.target);
};
$('#sitebtn').onclick = pageCmd(false);
$('#audiobtn').onclick = pageCmd(true);
$('#sharebtn').onclick = async (e) => {
  try { await chrome.downloads.download({ url: shareDirectUrl(tab.url), saveAs: false }); e.target.textContent = 'Started ✓'; }
  catch { e.target.textContent = 'Failed – open the link and download manually'; }
};

chrome.storage.session.onChanged.addListener((ch) => {
  if (tab && ch[tabKey(tab.id)]) render(ch[tabKey(tab.id)].newValue);
});
$('#refresh').onclick = load;
$('#clear').onclick = () => chrome.runtime.sendMessage({ type: MSG.CLEAR, tabId: tab.id });
load();
