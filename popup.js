'use strict';
const fileName = (u) => {
  try {
    const x = new URL(u);
    return decodeURIComponent(x.pathname.split('/').pop() || x.hostname) + (x.search.length > 1 && x.search.length < 30 ? x.search : '');
  } catch {
    return u;
  }
};
const host = (u) => {
  try { return new URL(u).hostname; } catch { return ''; }
};

const MIME_EXT = { 'audio/mpeg': 'mp3', 'audio/mp4': 'm4a', 'audio/x-m4a': 'm4a', 'audio/aac': 'aac', 'audio/ogg': 'ogg', 'audio/opus': 'opus', 'audio/flac': 'flac', 'audio/wav': 'wav', 'audio/x-wav': 'wav', 'video/quicktime': 'mov', 'video/x-matroska': 'mkv' };
let tab;

async function copy(text, btn, done = 'Copied') {
  try { await navigator.clipboard.writeText(text); } catch { $('#cmd').select(); document.execCommand('copy'); }
  btn.textContent = done;
}

function row(badge, title, sub, buttons) {
  const el = document.createElement('div');
  el.className = 'row';
  el.innerHTML = '<span class="badge"></span><div class="meta"><div class="t"></div><div class="s"></div></div><div class="btns"></div>';
  const b = el.querySelector('.badge');
  b.textContent = badge;
  b.classList.add('b-' + badge);
  el.querySelector('.t').textContent = title;
  el.querySelector('.t').title = title;
  el.querySelector('.s').textContent = sub;
  for (const [label, fn, cls, tip] of buttons) {
    const btn = document.createElement('button');
    btn.textContent = label;
    if (cls) btn.className = cls;
    if (tip) btn.title = tip;
    btn.onclick = fn;
    el.querySelector('.btns').append(btn);
  }
  return el;
}

function openDownloader(it) {
  const q = new URLSearchParams({
    url: it.url, kind: it.kind, tab: tab.id, frame: it.frameId || 0,
    referer: (it.hdr && it.hdr.referer) || tab.url || '', title: tab.title || '',
  });
  chrome.tabs.create({ url: chrome.runtime.getURL('downloader.html?' + q) });
}

async function directDownload(it, btn) {
  const m = /\.([a-z0-9]{2,4})$/i.exec(new URL(it.url).pathname);
  // Extensionless URLs (Drive /videoplayback): trust the MIME type (response header, else ?mime=).
  const mime = (it.ct || new URL(it.url).searchParams.get('mime') || '').split(';')[0].trim().toLowerCase();
  const ext = m ? m[1] : MIME_EXT[mime] || { mp4: 'mp4', webm: 'webm', audio: 'm4a' }[it.kind] || 'mp4';
  const title = safe((tab.title || '').replace(/ - Google Drive$/, ''));
  const r = await chrome.runtime.sendMessage({
    type: MSG.DIRECT_DOWNLOAD, url: it.url, tabId: tab.id, filename: `${title}.${ext}`,
  });
  btn.textContent = r && r.error ? 'Failed' : 'Started';
  if (r && r.error) btn.title = r.error;
}

